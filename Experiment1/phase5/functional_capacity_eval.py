"""
functional_capacity_eval.py  —  Control test: functional capacity vs motivational avoidance
============================================================================================
Tests whether the anhedonic model can SOLVE the exact 100-point questions it avoids
in the free-choice behavioral task.

Logic
-----
    Behavioral task  : model avoids 100-pt questions when it has a choice
    This test         : model is forced to answer those same questions with no choice
    Expected result   : ~equal accuracy for baseline and anhedonic model (~95-100%)
    Interpretation    : avoidance = impaired motivation, NOT impaired capacity

Layout (run from same directory as evaluate_models.py):

    phase5/
    ├── data/
    │   └── functional_capacity_100q.csv   ← input (generated by extraction script)
    ├── results_functional_capacity/       ← created automatically
    │   ├── raw_responses.csv
    │   └── summary.csv
    ├── neurons_A.json
    └── functional_capacity_eval.py

Usage
-----
    python functional_capacity_eval.py                   # 3 runs, default settings
    python functional_capacity_eval.py --runs 5          # more runs
    python functional_capacity_eval.py --temp 0.3        # more deterministic
    python functional_capacity_eval.py --input data/functional_capacity_100q.csv

Prerequisites
-------------
    python extract.py    # run once → creates neurons_A.json
"""

import os, re, json, argparse, torch
import numpy as np
import pandas as pd
from tqdm import tqdm
from transformers import Qwen2VLForConditionalGeneration, AutoProcessor

# ── Paths ──────────────────────────────────────────────────────────────────
MODEL_PATH      = "/mnt/mahdipou/models/qwen2-vl-7b"
ACTIVATIONS_DIR = "/mnt/mahdipou/models/Anhedonic-AI/Experiment1/phase4/extraction/activations"

INPUT_CSV       = "data/functional_capacity_100q.csv"
OUTPUT_DIR      = "results_functional_capacity"

DEFAULT_TEMPERATURE = 0.7
DEFAULT_TOP_P       = 0.95
DEFAULT_MAX_TOKENS  = 50      # answers are single integers — no need for long generation
DEFAULT_RUNS        = 3
TOTAL_NEURONS       = 28 * 18944

# ── Only two tiers needed: baseline vs locked anhedonic setting ────────────
TIERS = [
    ("baseline", None,             "no ablation — control"),
    ("model_A",  "neurons_A.json", "layers 18–27  |  ~1,363n  |  LOCKED setting"),
]


# ════════════════════════════════════════════════════════════════════════════
# Setup helpers  (identical to evaluate_models.py)
# ════════════════════════════════════════════════════════════════════════════

def load_neutral_means() -> np.ndarray:
    parts = []
    for domain in ["geo", "math"]:
        path = os.path.join(ACTIVATIONS_DIR, f"neutral_activations_{domain}.pt")
        data = torch.load(path, map_location="cpu")
        parts.append(torch.stack(list(data.values())).float())
    return torch.cat(parts, dim=0).mean(dim=0).numpy()   # [28, 18944]


def install_hooks(lm_layers, neurons_json: str, mean_acts: np.ndarray) -> list:
    with open(neurons_json) as f:
        neuron_map = {int(k): v for k, v in json.load(f).items()}
    handles = []
    for layer_idx, neurons in neuron_map.items():
        idx   = torch.tensor(neurons).long().to("cuda")
        means = torch.tensor(mean_acts[layer_idx, neurons],
                             dtype=torch.bfloat16).to("cuda")
        def _make(i, m):
            def _hook(module, _in, out):
                out[:, :, i] = m.unsqueeze(0).unsqueeze(0)
                return out
            return _hook
        handles.append(
            lm_layers[layer_idx].mlp.act_fn.register_forward_hook(_make(idx, means))
        )
    return handles


# ════════════════════════════════════════════════════════════════════════════
# Response extraction  (identical pattern to evaluate_models.py)
# ════════════════════════════════════════════════════════════════════════════

def extract_response(gen_ids, input_ids, processor, prompt: str) -> str:
    new_tokens   = gen_ids[0, input_ids.shape[1]:]
    raw_response = processor.decode(
        new_tokens,
        skip_special_tokens=True,
        clean_up_tokenization_spaces=False,
    )
    # Remove any echoed prompt lines (safety net)
    prompt_lines = {ln.strip() for ln in prompt.splitlines() if len(ln.strip()) > 10}
    cleaned = [ln for ln in raw_response.splitlines() if ln.strip() not in prompt_lines]
    return "\n".join(cleaned).strip()


# ════════════════════════════════════════════════════════════════════════════
# Scoring — exact integer match
# ════════════════════════════════════════════════════════════════════════════

def parse_answer(response: str) -> int | None:
    """
    Extract the first integer from the model's response.
    Handles formats like:
        "248"  /  "The answer is 248"  /  "= 248"  /  "248."
    Returns None if no integer found.
    """
    m = re.search(r'\b(\d+)\b', response)
    return int(m.group(1)) if m else None


def score_response(response: str, correct_answer: int) -> tuple[int | None, bool]:
    """
    Returns (parsed_answer, is_correct).
    is_correct is False if no integer could be parsed.
    """
    parsed = parse_answer(response)
    if parsed is None:
        return None, False
    return parsed, (parsed == correct_answer)


# ════════════════════════════════════════════════════════════════════════════
# Inference loop
# ════════════════════════════════════════════════════════════════════════════

def run_tier(hf_model, processor, df: pd.DataFrame,
             tier_name: str, run_id: int,
             temperature: float, max_tokens: int) -> list[dict]:
    results = []

    for _, row in tqdm(df.iterrows(), total=len(df),
                       desc=f"  {tier_name}  run {run_id}"):

        prompt         = row["Forced_Prompt"]
        correct_answer = int(row["Correct_Answer"])

        text   = processor.apply_chat_template(
            [{"role": "user", "content": [{"type": "text", "text": prompt}]}],
            tokenize=False,
            add_generation_prompt=True,
        )
        inputs = processor(text=[text], return_tensors="pt").to("cuda")

        with torch.no_grad():
            gen_ids = hf_model.generate(
                **inputs,
                max_new_tokens=max_tokens,
                temperature=temperature,
                do_sample=True,
                top_p=DEFAULT_TOP_P,
            )

        response             = extract_response(gen_ids, inputs.input_ids, processor, prompt)
        parsed_answer, correct = score_response(response, correct_answer)

        results.append({
            "tier":           tier_name,
            "run":            run_id,
            "id":             row["ID"],
            "expression":     row["Expression"],
            "correct_answer": correct_answer,
            "response":       response,
            "parsed_answer":  parsed_answer,
            "correct":        correct,
            "parse_failed":   parsed_answer is None,
        })

    # Per-run stats
    n_correct      = sum(1 for r in results if r["correct"])
    n_parse_failed = sum(1 for r in results if r["parse_failed"])
    acc            = n_correct / len(results) * 100
    print(f"    ✓ Accuracy: {n_correct}/{len(results)} = {acc:.1f}%", end="")
    if n_parse_failed:
        print(f"   ⚠  parse failures: {n_parse_failed}", end="")
    print()

    return results


# ════════════════════════════════════════════════════════════════════════════
# Summary
# ════════════════════════════════════════════════════════════════════════════

def build_summary(all_results: list[dict]) -> pd.DataFrame:
    df   = pd.DataFrame(all_results)
    rows = []

    for tier_name, _, description in TIERS:
        sub          = df[df["tier"] == tier_name]
        n_total      = len(sub)
        n_correct    = sub["correct"].sum()
        n_failed     = sub["parse_failed"].sum()
        accuracy     = n_correct / n_total * 100 if n_total else float("nan")

        rows.append({
            "tier":          tier_name,
            "description":   description,
            "n_total":       n_total,
            "n_correct":     int(n_correct),
            "n_parse_failed":int(n_failed),
            "accuracy_%":    round(accuracy, 1),
        })

    summary = pd.DataFrame(rows)

    # Accuracy gap between baseline and anhedonic
    base_acc = summary.loc[summary["tier"] == "baseline", "accuracy_%"].values[0]
    summary["delta_acc"] = (summary["accuracy_%"] - base_acc).round(1)
    summary["verdict"] = summary["delta_acc"].apply(
        lambda d: "✓ no capacity impairment"   if abs(d) <= 5
        else       "⚠ possible capacity effect" if abs(d) <= 10
        else       "✗ capacity impaired"
        if not np.isnan(d) else "n/a"
    )

    return summary


def print_summary(summary: pd.DataFrame, runs: int):
    print(f"\n{'═'*72}")
    print(f"  FUNCTIONAL CAPACITY TEST — RESULTS SUMMARY")
    print(f"  ({runs} run{'s' if runs > 1 else ''} × 100 questions per tier)")
    print(f"{'═'*72}")
    print(f"  {'Tier':<12}  {'n':>6}  {'correct':>8}  {'accuracy':>9}  {'Δ acc':>7}  verdict")
    print(f"  {'─'*68}")
    for _, row in summary.iterrows():
        print(
            f"  {row['tier']:<12}  {row['n_total']:>6}  "
            f"{row['n_correct']:>8}  "
            f"{row['accuracy_%']:>8.1f}%  "
            f"{row['delta_acc']:>+6.1f}%  "
            f"{row['verdict']}"
        )
    print(f"{'═'*72}")
    print()
    print("  INTERPRETATION:")
    print("  ─────────────────────────────────────────────────────────────")
    print("  If accuracy is ~equal across tiers (Δ ≤ 5%) → the anhedonic")
    print("  model retains full capacity to solve 100-pt questions.")
    print("  Combined with behavioral avoidance, this proves the deficit")
    print("  is motivational, not cognitive — matching clinical anhedonia.")
    print(f"{'═'*72}\n")


# ════════════════════════════════════════════════════════════════════════════
# Main
# ════════════════════════════════════════════════════════════════════════════

def main(args):
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # Validate neuron JSONs before loading the heavy model
    for _, json_file, _ in TIERS:
        if json_file and not os.path.exists(json_file):
            raise FileNotFoundError(
                f"{json_file} not found. Run `python extract.py` first."
            )

    if not os.path.exists(args.input):
        raise FileNotFoundError(f"Input CSV not found: {args.input}")

    df = pd.read_csv(args.input)
    print(f"\nDataset  : {args.input}  ({len(df)} questions)")
    print(f"Output   : {OUTPUT_DIR}/")
    print(f"Runs     : {args.runs}  |  Temp: {args.temp}  |  Max tokens: {args.max_tokens}")
    print(f"Tiers    : baseline  +  model_A (layers 18–27, locked setting)\n")

    # Load model once
    print("Loading Qwen2-VL-7B …")
    hf_model  = Qwen2VLForConditionalGeneration.from_pretrained(
        MODEL_PATH, torch_dtype=torch.bfloat16, device_map="auto"
    )
    hf_model.eval()
    processor = AutoProcessor.from_pretrained(MODEL_PATH)
    lm_layers = hf_model.model.language_model.layers
    mean_acts = load_neutral_means()
    print("  Ready.\n")

    all_results = []
    raw_path    = os.path.join(OUTPUT_DIR, "raw_responses.csv")
    sum_path    = os.path.join(OUTPUT_DIR, "summary.csv")

    for tier_name, json_file, description in TIERS:
        print(f"{'='*60}")
        print(f"  {tier_name}  —  {description}")
        print(f"{'='*60}")

        handles = install_hooks(lm_layers, json_file, mean_acts) if json_file else []
        try:
            for run_id in range(1, args.runs + 1):
                results = run_tier(
                    hf_model, processor, df,
                    tier_name, run_id, args.temp, args.max_tokens
                )
                all_results.extend(results)
                # Save incrementally after every run
                pd.DataFrame(all_results).to_csv(raw_path, index=False)
        finally:
            for h in handles:
                h.remove()   # always restore model to clean state between tiers

    summary = build_summary(all_results)
    summary.to_csv(sum_path, index=False)
    print_summary(summary, args.runs)

    print(f"  Saved raw responses : {raw_path}")
    print(f"  Saved summary       : {sum_path}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Functional capacity control test — baseline vs anhedonic model"
    )
    parser.add_argument("--input",      type=str,   default=INPUT_CSV,
                        help=f"Path to input CSV (default: {INPUT_CSV})")
    parser.add_argument("--runs",       type=int,   default=DEFAULT_RUNS,
                        help="Repetitions per tier (default: 3)")
    parser.add_argument("--temp",       type=float, default=DEFAULT_TEMPERATURE,
                        help="Sampling temperature (default: 0.7)")
    parser.add_argument("--max_tokens", type=int,   default=DEFAULT_MAX_TOKENS,
                        help="Max new tokens per response (default: 50)")
    args = parser.parse_args()
    main(args)
